// Writes docs/EXERCISE_ART_BRIEF.md: the illustrator's to-do list, generated from data/exercises.json
// and from what is already delivered in assets/exercises/.
//
//   node tools/art/exercise-brief.mjs           # rewrite the brief
//   node tools/art/exercise-brief.mjs --check   # exit 1 if the committed brief is out of date (npm run check)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const OUT = 'docs/EXERCISE_ART_BRIEF.md';
/** The exercises the beginner plan schedules (src/domain/plan.ts), drawn first. */
const PLAN = ['squat', 'incline-push-up', 'row', 'band-row', 'prone-y-raise', 'hip-hinge', 'plank'];
const VIEW = { side: 'side view', front: 'front view', back: 'back view', above: 'from above' };

const exercises = JSON.parse(readFileSync('data/exercises.json', 'utf8'));
const byId = new Map(exercises.map((e) => [e.id, e]));
const linked = new Set(PLAN.flatMap((id) => [byId.get(id)?.easierId, byId.get(id)?.harderId]).filter(Boolean));
const batchOf = (e) => (PLAN.includes(e.id) ? 1 : linked.has(e.id) || e.requires.length === 0 ? 2 : 3);
const files = (e) => [
  { name: 'start.png', what: `${e.artBrief.frames[0].label}: ${e.artBrief.frames[0].pose}` },
  { name: 'end.png', what: `${e.artBrief.frames[1].label}: ${e.artBrief.frames[1].pose}` },
  ...e.mistakes.map((m, i) => ({
    name: `mistake-${i + 1}.png`,
    what: `Wrong on purpose (${VIEW[m.view]}): **${m.title}.** ${m.looksLike}`,
  })),
];
const delivered = (e, file) => existsSync(`assets/exercises/${e.id}/${file}`);

const ordered = [...exercises].sort((a, b) => batchOf(a) - batchOf(b) || PLAN.indexOf(a.id) - PLAN.indexOf(b.id));
const total = ordered.reduce((n, e) => n + files(e).length, 0);
const done = ordered.reduce((n, e) => n + files(e).filter((f) => delivered(e, f.name)).length, 0);

const lines = [
  '# Exercise art brief',
  '',
  `Generated by \`tools/art/exercise-brief.mjs\` from \`data/exercises.json\`. Do not edit by hand. **${done} of ${total} images delivered.**`,
  '',
  'This is a request for production art, not a claim that it exists. Until a file is delivered, the app shows the interim concept crop or a neutral icon, plus the full text guidance.',
  '',
  '## What to draw',
  '',
  'For every exercise:',
  '- **`start.png` and `end.png`:** the two key positions of a correct rep, from the camera view given.',
  '- **`mistake-<n>.png`:** one image per common mistake, showing that fault clearly but realistically, from the view given. The app puts it next to the written fix, so the image itself has no red cross, arrows or text.',
  '',
  '## Spec (same for every file)',
  '- **Character:**',
  '  - The canonical Blob: warm cream-white soft clay, two upright black pill eyes, no mouth, nose, hair or ears.',
  '  - **Black athletic shorts**, beginner build (S0–S1), same proportions in every frame.',
  '  - No extra muscles, no recolors.',
  '  - See `docs/BLOB_CHARACTER_VISUAL_BIBLE.md` and `docs/ILLUSTRATION_EXPORT_SPEC.md`.',
  '- **Canvas:**',
  '  - 1600 × 1600 px transparent RGBA PNG (the short edge must be at least 1024 px).',
  '  - At least 8% transparent padding on every side; nothing touches the edge.',
  '  - No background, floor plane, shadow box, text, logo or watermark.',
  '  - A soft contact shadow under the feet is fine.',
  '- **Camera and scale:**',
  '  - Orthographic-feeling camera at hip height, using the view listed for that file.',
  '  - Same scale for `start`, `end` and the mistakes of one exercise, so they can be compared side by side.',
  '- **Props:**',
  '  - Simple, neutral and realistic: dark grey dumbbells, a muted band with its anchor visible, plain bench or chair, plain wall edge.',
  '  - No brand marks.',
  '- **Technique:** the correct frames must match the text exactly, because a coach will review both. When the text and a drawing disagree, the text wins; flag it in issue #1.',
  '',
  '## Delivery',
  '- **Path:** `assets/exercises/<exercise-id>/<file>`, for example `assets/exercises/squat/start.png`.',
  '- **Upload:**',
  '  - Upload through the GitHub web UI on branch `claude/zealous-cannon-9cvkob`: Add file → Upload files, into the folder path above.',
  '  - Or give the founder a ZIP with the same folder layout.',
  '- **After upload:** Claude runs `npm run art:sync`. That validates every file, makes optimized WebP copies and wires them into the app, and reports any file it skipped and why.',
  '- **Order:** deliver in batches.',
  '  - Batch 1 is the exercises in the beginner plan.',
  '  - Batch 2 is their easier/harder variations and the bodyweight movements.',
  '  - Batch 3 is the rest.',
  '  - Within an exercise, `start` and `end` come before the mistakes.',
  '',
  '## Acceptance',
  '- Every file resolves on GitHub at the exact path listed below.',
  '- `npm run art:sync` reports no skipped files.',
  '- The character lock holds in every frame, including black shorts.',
  '- The pose matches the written description and the exercise text.',
  '',
  '## Checklist',
  '',
  '| Batch | Exercise | id | View | Delivered |',
  '|---|---|---|---|---|',
  ...ordered.map((e) => {
    const list = files(e);
    const have = list.filter((f) => delivered(e, f.name)).length;
    return `| ${batchOf(e)} | ${e.name} | \`${e.id}\` | ${VIEW[e.artBrief.view]} | ${have}/${list.length} |`;
  }),
  '',
];

for (const batch of [1, 2, 3]) {
  lines.push(`## Batch ${batch}`, '');
  for (const e of ordered.filter((item) => batchOf(item) === batch)) {
    lines.push(`### ${e.name} (\`${e.id}\`), ${VIEW[e.artBrief.view]}`, '');
    lines.push(`Equipment: ${e.equipment}. Setup: ${e.startingPosition}`, '');
    for (const file of files(e)) {
      const mark = delivered(e, file.name) ? '[x]' : '[ ]';
      lines.push(`- ${mark} \`assets/exercises/${e.id}/${file.name}\`: ${file.what}`);
    }
    lines.push('');
  }
}

const text = lines.join('\n');
if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error(`${OUT} is out of date. Run: node tools/art/exercise-brief.mjs`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${done}/${total} images delivered).`);
} else {
  writeFileSync(OUT, text);
  console.log(`Wrote ${OUT}: ${ordered.length} exercises, ${total} images, ${done} delivered.`);
}
