#!/usr/bin/env python3
"""Turns delivered exercise art into app-ready frames and regenerates src/components/exerciseFrames.ts.

    npm run art:sync            # or: python3 tools/art/sync_exercise_art.py

Input (delivered by the illustrator, see docs/EXERCISE_ART_BRIEF.md):
    assets/exercises/<exercise-id>/start.png      artBrief.frames[0]
    assets/exercises/<exercise-id>/end.png        artBrief.frames[1]
    assets/exercises/<exercise-id>/mistake-<n>.png  exercise.mistakes[n-1], drawn wrong on purpose

Output:
    assets/exercises/build/<exercise-id>/<name>.webp   900 x 900, WebP quality 86, alpha kept
    src/components/exerciseFrames.ts                   typed registry the app imports

Image generators never place two frames exactly alike, and the app cross-fades start -> end to show
the movement. So every frame of one exercise is re-laid out the same way: one shared scale (the
largest pose fills 84% of the canvas), and the ground contact (the lowest band of the body: feet,
or hands and feet) centred at the same point near the bottom. Relative sizes between frames are kept.

Every input is checked first. A file that fails (wrong size, no transparency, unknown exercise or
mistake number) is reported and skipped; the rest still sync. Exit code 1 if anything was skipped.
"""
from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'assets' / 'exercises'
BUILD = SOURCE / 'build'
REGISTRY = ROOT / 'src' / 'components' / 'exerciseFrames.ts'
MIN_EDGE = 1024
OUT = 900
FILL = 0.84
BASELINE = 0.93
NAME = re.compile(r'^(start|end|mistake-([1-9]))\.png$')

HEADER = """// Generated by tools/art/sync_exercise_art.py from assets/exercises/. Do not edit by hand.
// Run `npm run art:sync` after adding or replacing exercise art.
import type { ArtAsset } from './art';

export interface ExerciseFrameSet {
  /** Matches artBrief.frames[0] (e.g. "Top"). */
  start?: ArtAsset;
  /** Matches artBrief.frames[1] (e.g. "Bottom"); also used for thumbnails. */
  end?: ArtAsset;
  /** mistakes[i] shows exercise.mistakes[i] (the fault, drawn wrong on purpose). */
  mistakes: (ArtAsset | null)[];
}
"""


def check(path: Path, image: Image.Image) -> str | None:
    if image.mode not in ('RGBA', 'LA') and 'transparency' not in image.info:
        return 'needs a transparent background (RGBA PNG)'
    rgba = image.convert('RGBA')
    if min(rgba.size) < MIN_EDGE:
        return f'is {rgba.width}x{rgba.height}; the short edge must be at least {MIN_EDGE}px'
    w, h = rgba.size
    corners = [rgba.getpixel((0, 0)), rgba.getpixel((w - 1, 0)), rgba.getpixel((0, h - 1)), rgba.getpixel((w - 1, h - 1))]
    if any(pixel[3] > 8 for pixel in corners):
        return 'has an opaque background; the corners must be transparent'
    box = rgba.getchannel('A').getbbox()
    if box is None:
        return 'is empty'
    if box[0] == 0 or box[1] == 0 or box[2] == w or box[3] == h:
        return 'touches the edge of the canvas; leave transparent padding so nothing is clipped'
    return None


def ground_contact_x(rgba: Image.Image) -> float:
    """Horizontal centre of the lowest 5% of the figure: where it meets the floor."""
    alpha = rgba.getchannel('A')
    band = max(1, rgba.height // 20)
    columns = [x for y in range(rgba.height - band, rgba.height) for x in range(rgba.width) if alpha.getpixel((x, y)) > 24]
    return sum(columns) / len(columns) if columns else rgba.width / 2


def main() -> int:
    exercises = {e['id']: e for e in json.loads((ROOT / 'data' / 'exercises.json').read_text())}
    problems: list[str] = []
    registry: dict[str, dict] = {}
    frames: dict[str, list] = {}
    if BUILD.exists():
        shutil.rmtree(BUILD)
    folders = sorted(p for p in SOURCE.iterdir() if p.is_dir() and p.name not in ('build', 'inbox')) if SOURCE.exists() else []
    for folder in folders:
        exercise = exercises.get(folder.name)
        if exercise is None:
            problems.append(f'{folder.name}/: no exercise with this id in data/exercises.json')
            continue
        for path in sorted(folder.iterdir()):
            match = NAME.match(path.name)
            rel = path.relative_to(ROOT)
            if not match:
                if path.name not in ('README.md', '.gitkeep'):
                    problems.append(f'{rel}: unexpected file name (use start.png, end.png or mistake-<n>.png)')
                continue
            if match.group(2) and int(match.group(2)) > len(exercise['mistakes']):
                problems.append(f'{rel}: {exercise["name"]} has only {len(exercise["mistakes"])} mistakes')
                continue
            try:
                image = Image.open(path)
                image.load()
            except Exception as error:  # noqa: BLE001 - report any unreadable file
                problems.append(f'{rel}: cannot be read ({error})')
                continue
            issue = check(path, image)
            if issue:
                problems.append(f'{rel} {issue}')
                continue
            frames.setdefault(folder.name, []).append((path.stem, match.group(2), image.convert('RGBA')))

    for exercise_id, items in frames.items():
        boxes = [rgba.getchannel('A').point(lambda a: 255 if a > 24 else 0).getbbox() for _, _, rgba in items]
        scale = min(OUT * FILL / max(box[2] - box[0], box[3] - box[1]) for box in boxes)
        for (stem, mistake, rgba), box in zip(items, boxes):
            cut = rgba.crop(box)
            cut = cut.resize((max(1, round(cut.width * scale)), max(1, round(cut.height * scale))), Image.LANCZOS)
            anchor = ground_contact_x(cut)
            canvas = Image.new('RGBA', (OUT, OUT), (0, 0, 0, 0))
            x = round(OUT / 2 - anchor)
            x = min(max(x, 0), OUT - cut.width)
            y = max(0, round(OUT * BASELINE) - cut.height)
            canvas.alpha_composite(cut, (x, y))
            out = BUILD / exercise_id / f'{stem}.webp'
            out.parent.mkdir(parents=True, exist_ok=True)
            canvas.save(out, 'WEBP', quality=86, method=6)
            entry = registry.setdefault(exercise_id, {'mistakes': {}})
            asset = (f"{{ source: require('@/assets/exercises/build/{exercise_id}/{stem}.webp'), "
                     f'width: {OUT}, height: {OUT} }}')
            if mistake:
                entry['mistakes'][int(mistake)] = asset
            else:
                entry[stem] = asset

    lines = [HEADER, 'export const EXERCISE_FRAMES: Record<string, ExerciseFrameSet> = {']
    for exercise_id in sorted(registry):
        entry = registry[exercise_id]
        lines.append(f"  '{exercise_id}': {{")
        for key in ('start', 'end'):
            if key in entry:
                lines.append(f'    {key}: {entry[key]},')
        count = max(entry['mistakes'], default=0)
        items = [entry['mistakes'].get(n, 'null') for n in range(1, count + 1)]
        lines.append('    mistakes: [' + ''.join(f'\n      {item},' for item in items) + ('\n    ],' if items else '],'))
        lines.append('  },')
    lines.append('};\n')
    text = '\n'.join(lines).replace('{\n};', '{};')
    REGISTRY.write_text(text)

    delivered = sum(len(e['mistakes']) + ('start' in e) + ('end' in e) for e in registry.values())
    print(f'Synced {delivered} image(s) for {len(registry)} exercise(s) into {REGISTRY.relative_to(ROOT)}.')
    if problems:
        print('\nSkipped:', file=sys.stderr)
        for problem in problems:
            print(f'  - {problem}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
